package paq.proyecto;

/**
 *
 * @author aleja
 */
public abstract class Persona 
{
    protected int dni;
    protected String nom, apell;

    public Persona(int dni, String nom, String apell) {
        this.dni = dni;
        this.nom = nom;
        this.apell = apell;
    }

    public int getDni() {
        return dni;
    }

    public void setDni(int dni) {
        this.dni = dni;
    }

    public String getNom() {
        return nom;
    }

    public void setNom(String nom) {
        this.nom = nom;
    }

    public String getApell() {
        return apell;
    }

    public void setApell(String apell) {
        this.apell = apell;
    }
    
}
